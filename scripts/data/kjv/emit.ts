import type { BookText, KjvIndex, KjvTotals, TranslationInfo } from "../../../src/lib/bible/types";
import { countWords } from "./validate";

/** Bump when the shape of public/data/kjv changes. */
export const KJV_SCHEMA_VERSION = 1;

/** public/data/kjv/books/{ID}.json: minified, one line. */
export function formatBookJson(book: BookText): string {
  return `${JSON.stringify(book)}\n`;
}

export function buildIndex(
  books: readonly BookText[],
  translation: TranslationInfo,
  totals: KjvTotals,
  generatedAt: string,
): KjvIndex {
  return {
    schemaVersion: KJV_SCHEMA_VERSION,
    translation: { ...translation, generatedAt },
    books: books.map((book) => ({
      id: book.id,
      chapters: book.chapters.map((c) => c.verses.length),
      words: book.chapters.reduce(
        (sum, c) => sum + c.verses.reduce((s, v) => s + countWords(v.t), 0),
        0,
      ),
    })),
    totals,
  };
}

/** index.json with one book per line, so regenerated data diffs readably. */
export function formatIndexJson(index: KjvIndex): string {
  const translation = JSON.stringify(index.translation, null, 2).replace(/\n/g, "\n  ");
  return [
    "{",
    `  "schemaVersion": ${index.schemaVersion},`,
    `  "translation": ${translation},`,
    `  "books": [`,
    index.books.map((b) => `    ${JSON.stringify(b)}`).join(",\n"),
    "  ],",
    `  "totals": ${JSON.stringify(index.totals)}`,
    "}",
    "",
  ].join("\n");
}

const key = (id: string) => (/^[A-Za-z_$][\w$]*$/.test(id) ? id : JSON.stringify(id));

/** src/lib/bible/generated/kjv-meta.ts */
export function formatMetaModule(index: KjvIndex): string {
  // generatedAt stays out of the module so it only changes when the data does.
  const { id, name, edition, license, source, sourceUrl, sha256 } = index.translation;
  const translation: TranslationInfo = { id, name, edition, license, source, sourceUrl, sha256 };
  const t = index.totals;
  return [
    "// Generated by scripts/data/kjv.ts. Do not edit; run `npm run data:kjv` to regenerate.",
    `// Source: ${translation.sourceUrl} (sha256 ${translation.sha256}), public domain.`,
    "",
    'import type { BookId } from "../canon";',
    'import type { KjvTotals, TranslationInfo } from "../types";',
    "",
    "/** Verses per chapter: `VERSE_COUNTS.REV[11]` is Revelation 12. */",
    "export const VERSE_COUNTS: Readonly<Record<BookId, readonly number[]>> = {",
    ...index.books.map((b) => `  ${key(b.id)}: [${b.chapters.join(", ")}],`),
    "};",
    "",
    "/** Words per book: whitespace-delimited tokens of verse text (titles, colophons, notes excluded). */",
    "export const WORD_COUNTS: Readonly<Record<BookId, number>> = {",
    ...index.books.map((b) => `  ${key(b.id)}: ${b.words},`),
    "};",
    "",
    "export const KJV_TOTALS: Readonly<KjvTotals> = {",
    `  books: ${t.books},`,
    `  chapters: ${t.chapters},`,
    `  verses: ${t.verses},`,
    `  words: ${t.words},`,
    "};",
    "",
    "/** Where the text comes from; credit it wherever KJV text is shown. */",
    "export const KJV_TRANSLATION: Readonly<TranslationInfo> = {",
    ...Object.entries(translation).map(([k, v]) => `  ${key(k)}: ${JSON.stringify(v)},`),
    "};",
    "",
  ].join("\n");
}
