/**
 * The study catalogue as Markdown, generated from src/studies/registry.ts:
 *
 * - a compact gallery of the live studies for the README, between the
 *   GALLERY_START and GALLERY_END markers;
 * - docs/STUDIES.md, every study (live and planned) by category.
 *
 * Pure functions, so the tests can check the committed files are up to date.
 * Write them with `npm run docs:studies`; take the pictures with
 * `npm run docs:shots`.
 */
import { SITE } from "../../src/lib/site";
import type { Category, Study } from "../../src/studies/registry";

export const GALLERY_START =
  "<!-- studies:start · generated by `npm run docs:studies` from src/studies/registry.ts; don't edit by hand -->";
export const GALLERY_END = "<!-- studies:end -->";

/** Studies per gallery row. Three thumbnails fit GitHub's README width. */
const COLUMNS = 3;
const THUMB_WIDTH = 280;

/** The README's cover picture: the top of the index page. */
export const COVER_IMAGE = "docs/images/cover.jpg";

/** Where a study's picture is kept, relative to the repository root. */
export function previewImagePath(slug: string): string {
  return `docs/images/studies/${slug}.jpg`;
}

function liveHref(study: Study): string {
  return `${SITE.liveUrl}${study.href ?? ""}`;
}

/** Text safe inside HTML in Markdown (titles and summaries are plain text). */
function html(text: string): string {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

export function liveOf(studies: readonly Study[]): Study[] {
  return studies.filter((s) => s.status === "live");
}

/** The README block, markers included. */
export function renderGallery(studies: readonly Study[]): string {
  const live = liveOf(studies);
  const planned = studies.length - live.length;
  const rows: string[] = [];
  for (let i = 0; i < live.length; i += COLUMNS) {
    const cells = live.slice(i, i + COLUMNS).map((study) => {
      const href = liveHref(study);
      return [
        `<td valign="top" width="${THUMB_WIDTH}">`,
        `<a href="${href}"><img src="${previewImagePath(study.slug)}" alt="${html(study.title)}" width="${THUMB_WIDTH}"></a><br>`,
        `<strong><a href="${href}">${html(study.title)}</a></strong><br>`,
        html(study.summary),
        `</td>`,
      ].join("\n");
    });
    rows.push(`<tr>\n${cells.join("\n")}\n</tr>`);
  }

  const table = live.length > 0 ? `<table>\n${rows.join("\n")}\n</table>\n\n` : "";
  const more =
    `[See every study](docs/STUDIES.md): ${live.length} live` +
    (planned > 0 ? ` and ${planned} planned.` : ".");
  return `${GALLERY_START}\n${table}${more}\n${GALLERY_END}`;
}

/** Replace the gallery between its markers; throws if the markers are missing. */
export function withGallery(readme: string, gallery: string): string {
  const start = readme.indexOf(GALLERY_START);
  const end = readme.indexOf(GALLERY_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error("README.md is missing the studies:start / studies:end markers");
  }
  return readme.slice(0, start) + gallery + readme.slice(end + GALLERY_END.length);
}

function renderLive(study: Study): string {
  const lines = [
    `### [${study.title}](${liveHref(study)})`,
    "",
    `<a href="${liveHref(study)}"><img src="images/studies/${study.slug}.jpg" alt="${html(study.title)}" width="640"></a>`,
    "",
    study.summary,
    "",
  ];
  if (study.facts?.length) {
    lines.push(...study.facts.map(([label, value]) => `- **${label}:** ${value}`), "");
  }
  if (study.sources?.length) {
    const sources = study.sources.map((source) => {
      const label = source.href ? `[${source.label}](${source.href})` : source.label;
      return source.license ? `${label} (${source.license})` : label;
    });
    lines.push(`Sources: ${sources.join("; ")}.`, "");
  }
  return lines.join("\n");
}

/** docs/STUDIES.md in full. */
export function renderCatalogue(studies: readonly Study[], categories: readonly Category[]): string {
  const live = liveOf(studies);
  const out = [
    "<!-- Generated by `npm run docs:studies` from src/studies/registry.ts; don't edit by hand. -->",
    "",
    "# Studies",
    "",
    `Every study in Scripture, by section: ${live.length} live and ` +
      `${studies.length - live.length} planned. Live studies open on [the site](${SITE.liveUrl}); ` +
      "planned ones are on the way. To suggest one, use the " +
      "[study form](../../../issues/new?template=suggest-a-study.yml).",
    "",
  ];
  for (const category of categories) {
    const inCategory = studies.filter((s) => s.category === category.id);
    if (inCategory.length === 0) continue;
    out.push(`## ${category.title}`, "", category.description, "");
    for (const study of inCategory.filter((s) => s.status === "live")) out.push(renderLive(study));
    const planned = inCategory.filter((s) => s.status !== "live");
    if (planned.length > 0) {
      out.push("Planned:", "", ...planned.map((s) => `- **${s.title}.** ${s.summary}`), "");
    }
  }
  return `${out.join("\n").trimEnd()}\n`;
}
