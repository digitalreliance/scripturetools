/** An irregular little island outline, the same every render. */
function islet([lon, lat, rx, ry]: readonly [number, number, number, number]): Pt[] {
  const wobble = [1, 0.82, 1.08, 0.9, 1.02, 0.86, 0.96];
  return wobble.map((k, i) => {
    const a = (i / wobble.length) * Math.PI * 2 + lon;
    return [lon + Math.cos(a) * rx * k, lat + Math.sin(a) * ry * k] as Pt;
  });
}

