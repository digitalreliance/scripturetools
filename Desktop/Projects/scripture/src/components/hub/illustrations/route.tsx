/**
 * Paul's voyage to Rome on an engraved chart of the eastern Mediterranean.
 * Hover sails the route port by port.
 */
export function route(ctx: Ctx): ReactNode {
  const { p, w, thumb, uid } = ctx;
  const proj = projection(24, 36.87, 160, 93.8, 13.6);
  const P = (pts: readonly Pt[]) => pts.map(proj);

  const mainland = [ITALY, BALKANS, EAST].map((poly) => line(P(poly), true)).join("");
  const islands = [SICILY, CRETE, CYPRUS, EUBOEA, ...ISLETS.map(islet)]
    .map((poly) => smooth(P(poly), true, 0.6))
    .join("");
  const land = mainland + islands;

  const stops = VOYAGE.map((s) => proj(s.at));
  const routeD = smooth(stops, false, 0.9);
  const at = fractions(stops);
  const sail = thumb ? 1300 : 1450;
  const road = line(P(ROAD));
  const rome = proj([12.5, 41.88]);
  const maskId = uid("sail");

  return (
    <g>
      {thumb ? null : (
        <>
          <WaterLines ctx={ctx} d={land} />
          <FrameTicks
            ctx={ctx}
            xs={[15, 20, 25, 30, 35].map((lon) => proj([lon, 36])[0])}
            ys={[35, 40].map((lat) => proj([24, lat])[1])}
          />
        </>
      )}
      <path
        d={land}
        fill={p.chrome}
        stroke={p.ink}
        strokeWidth={thumb ? w.hair : w.fine}
        strokeLinejoin="round"
      />

      {/* The sea route, dashed; a mask lets it draw itself on hover. */}
      <mask id={maskId} maskUnits="userSpaceOnUse" x={0} y={0} width={320} height={200}>
        <path
          d={routeD}
          stroke="#fff"
          strokeWidth={thumb ? 24 : 6}
          fill="none"
          strokeLinecap="round"
          pathLength={1}
          className={css.draw}
          style={timing(0, sail, LINEAR)}
        />
      </mask>
      <g mask={`url(#${maskId})`}>
        <path
          d={routeD}
          stroke={p.accent}
          strokeWidth={thumb ? w.base : w.base}
          strokeDasharray={thumb ? "14 9" : "3.2 2.2"}
          strokeLinecap="round"
          fill="none"
        />
      </g>
      <path
        d={road}
        stroke={p.accent}
        strokeWidth={thumb ? w.fine : w.fine}
        strokeDasharray={thumb ? "0.1 11" : "0.1 2.4"}
        strokeLinecap="round"
        fill="none"
        className={css.fade}
        style={timing(sail, 260)}
      />

      {VOYAGE.map((stop, i) => {
        if (!stop.port) return null;
        if (thumb && !["Caesarea", "Melita", "Puteoli"].includes(stop.port)) return null;
        const [x, y] = stops[i];
        const label = PORT_LABELS[stop.port];
        return (
          <g key={stop.port} className={css.pop} style={timing(at[i] * sail, 280)}>
            <circle
              cx={r2(x)}
              cy={r2(y)}
              r={thumb ? 9 : 2.1}
              fill={p.canvas}
              stroke={p.ink}
              strokeWidth={thumb ? w.fine : w.fine}
            />
            {!thumb && label ? (
              <Txt x={r2(x + label.dx)} y={r2(y + label.dy)} textAnchor={label.anchor ?? "start"} fill={p.ink}>
                {stop.port}
              </Txt>
            ) : null}
          </g>
        );
      })}

      {/* Rome, the destination. */}
      <g className={css.pop} style={timing(sail + 120, 300)}>
        <circle cx={r2(rome[0])} cy={r2(rome[1])} r={thumb ? 11 : 3} fill={p.accent} />
        {thumb ? null : (
          <Txt x={r2(rome[0] + 5)} y={r2(rome[1] + 2.4)} fill={p.ink} fontWeight={600}>
            Rome
          </Txt>
        )}
      </g>
    </g>
  );
}
